#!/usr/bin/env node

/**
 * Development Environment Config Generator
 *
 * This script reads your .env.local file and generates a browser-compatible
 * configuration file for development use.
 *
 * Usage: node generate-env-config.js
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

// Get current directory for ES modules
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function generateEnvConfig() {
  const envPath = path.join(__dirname, "..", ".env.local");

  try {
    // Check if .env.local exists
    if (!fs.existsSync(envPath)) {
      console.error("❌ .env.local file not found");
      console.log("Create a .env.local file with your Firebase configuration");
      return;
    }

    // Read and parse .env.local
    const envContent = fs.readFileSync(envPath, "utf8");
    const envVars = {};

    envContent.split("\n").forEach((line) => {
      line = line.trim();
      if (line && !line.startsWith("#")) {
        const [key, ...valueParts] = line.split("=");
        if (key && valueParts.length > 0) {
          envVars[key.trim()] = valueParts.join("=").trim();
        }
      }
    });

    // Generate browser-compatible config
    const configContent = `// Auto-generated environment configuration for development
// DO NOT EDIT THIS FILE MANUALLY - it's generated from .env.local
// Generated on: ${new Date().toISOString()}

window.ENV = {
  FIREBASE_API_KEY: "${envVars.FIREBASE_API_KEY || ""}",
  FIREBASE_AUTH_DOMAIN: "${envVars.FIREBASE_AUTH_DOMAIN || ""}",
  FIREBASE_PROJECT_ID: "${envVars.FIREBASE_PROJECT_ID || ""}",
  FIREBASE_STORAGE_BUCKET: "${envVars.FIREBASE_STORAGE_BUCKET || ""}",
  FIREBASE_MESSAGING_SENDER_ID: "${envVars.FIREBASE_MESSAGING_SENDER_ID || ""}",
  FIREBASE_APP_ID: "${envVars.FIREBASE_APP_ID || ""}",
  NODE_ENV: "${envVars.NODE_ENV || "development"}"
};

console.log('🔧 Development environment variables loaded');
`;

    // Write the config file
    const outputPath = path.join(__dirname, "firebase", "env-config.js");
    fs.writeFileSync(outputPath, configContent);

    console.log("✅ Environment config generated successfully");
    console.log(`📁 Config file: ${outputPath}`);
    console.log("🚀 Your Firebase config is now ready for development");
  } catch (error) {
    console.error("❌ Error generating environment config:", error.message);
  }
}

// Run the generator
generateEnvConfig();
